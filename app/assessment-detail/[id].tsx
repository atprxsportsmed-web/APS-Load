// ── Share summary builder ─────────────────────────────────────────────────────
// Produces a plain-text clinical handoff summary — no PII beyond what the
// coach entered. Available to all users; referral safety is never paywalled.

const RECOMMENDATION_LABELS: Record<string, string> = {
  green: 'Continue Training',
  yellow: 'Modify Today\'s Training',
  orange: 'Change Today\'s Session Goal',
  red: 'Stop and Seek Evaluation',
};

function buildShareSummary(assessment: Assessment): string {
  const lines: string[] = [];
  const LINE = '──────────────────────────────────────';

  lines.push('ATPRX Athlete Center — Session Summary');
  lines.push(LINE);
  lines.push('');

  // Date
  const date = new Date(assessment.createdAt).toLocaleDateString('en-US', {
    weekday: 'long', month: 'long', day: 'numeric', year: 'numeric',
  });
  lines.push(`Date: ${date}`);

  // Region / activity
  const region = BODY_REGIONS.find(r => r.value === assessment.symptomContext?.bodyRegion)?.label;
  if (region) lines.push(`Region: ${region}`);
  if (assessment.symptomContext?.activity) {
    lines.push(`Activity: ${assessment.symptomContext.activity}`);
  }

  // Safety flags (if any)
  const flags = assessment.safetyScreen?.selectedFlags ?? [];
  if (flags.length > 0) {
    const flagLabels = flags.map(id => URGENT_FLAGS.find(f => f.id === id)?.label ?? id);
    lines.push('');
    lines.push('Safety Flags Reported:');
    for (const fl of flagLabels) lines.push(`  • ${fl}`);
  }

  lines.push('');
  lines.push(`Recommendation: ${RECOMMENDATION_LABELS[assessment.classification] ?? assessment.classification}`);
  lines.push('');

  // Key findings
  if (assessment.classificationReasons.length > 0) {
    lines.push('Key Findings:');
    for (const r of assessment.classificationReasons) lines.push(`  • ${r}`);
  }

  // Referral level from rich decision (if present)
  const referralLevel = assessment.participationDecision?.referralLevel;
  if (referralLevel && referralLevel !== 'none') {
    lines.push('');
    const referralText: Record<string, string> = {
      emergency: 'EMERGENCY — Seek emergency medical care immediately',
      urgent_medical: 'URGENT — Seek same-day medical evaluation',
      sports_medicine: 'Sports Medicine evaluation recommended',
    };
    lines.push(`Referral: ${referralText[referralLevel] ?? referralLevel}`);
  }

  // Monitoring instructions
  if (assessment.participationDecision?.monitoringInstructions) {
    lines.push('');
    lines.push(`Monitoring: ${assessment.participationDecision.monitoringInstructions}`);
  }

  // Training modifications
  if (assessment.modifications.length > 0) {
    const modLabels = assessment.modifications
      .map(id => MODIFICATION_OPTIONS.find(o => o.id === id)?.label ?? id);
    lines.push('');
    lines.push(`Modifications Planned: ${modLabels.join(', ')}`);
  }

  // Follow-up
  if (assessment.followUp) {
    lines.push('');
    lines.push(`24-hr Follow-up: ${assessment.followUp.nextDayResponse.replace(/_/g, ' ')}`);
  }

  lines.push('');
  lines.push(LINE);
  lines.push('Generated by ATPRX Athlete Center');
  lines.push('This tool is a coach participation-decision support aid.');
  lines.push('It does not diagnose injuries or replace evaluation by a');
  lines.push('licensed healthcare professional.');

  return lines.join('\n');
}

// ── Section component ─────────────────────────────────────────────────────────

function Section({ title, children }: { title: string; children: React.ReactNode }) {
  const colors = useColors();
  return (
    <View style={[styles.section, { backgroundColor: colors.card, borderColor: colors.border, borderRadius: colors.radius }]}>
      <Text style={[styles.sectionTitle, { color: colors.foreground }]}>{title}</Text>
      {children}
    </View>
  );
}

export default function AssessmentDetailScreen() {
  const colors = useColors();
  const insets = useSafeAreaInsets();
  const { id } = useLocalSearchParams<{ id: string }>();
  const { getById, remove } = useHistory();

  const assessment = getById(id ?? '');

  const topPad = Platform.OS === 'web' ? 67 : insets.top;
  const bottomPad = Platform.OS === 'web' ? 34 : insets.bottom;

  if (!assessment) {
    return (
      <View style={[styles.container, { backgroundColor: colors.background }]}>
        <View style={[styles.header, { paddingTop: topPad + 12, backgroundColor: colors.primary }]}>
          <TouchableOpacity onPress={() => router.back()} style={styles.backBtn}>
            <Ionicons name="chevron-back" size={24} color="rgba(255,255,255,0.9)" />
          </TouchableOpacity>
          <Text style={styles.headerTitle}>Assessment</Text>
          <View style={styles.backBtn} />
        </View>
        <View style={{ flex: 1, alignItems: 'center', justifyContent: 'center' }}>
          <Text style={[{ color: colors.mutedForeground, fontFamily: 'Inter_400Regular', fontSize: 15 }]}>
            Not found.
          </Text>
        </View>
      </View>
    );
  }

  const regionLabel = BODY_REGIONS.find(r => r.value === assessment.symptomContext?.bodyRegion)?.label;
  const info = CLASSIFICATION_INFO[assessment.classification];
  const classColor = { green: colors.green, yellow: colors.yellow, orange: colors.orange, red: colors.red }[assessment.classification];

  const isStopRefer = assessment.classification === 'red';

  const handleShare = async () => {
    try {
      Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Light);
      const message = buildShareSummary(assessment);
      await Share.share({ message }, { subject: 'ATPRX Session Summary' });
    } catch {
      // User cancelled or share sheet unavailable — no error shown
    }
  };

  const handleDelete = () => {
    Alert.alert(
      'Delete Assessment',
      'Remove this assessment from history?',
      [
        { text: 'Cancel', style: 'cancel' },
        {
          text: 'Delete',
          style: 'destructive',
          onPress: async () => {
            Haptics.notificationAsync(Haptics.NotificationFeedbackType.Warning);
            await remove(assessment.id);
            router.back();
          },
        },
      ],
    );
  };

  const formatDate = (iso: string) =>
    new Date(iso).toLocaleDateString('en-US', {
      weekday: 'short', month: 'short', day: 'numeric', year: 'numeric',
      hour: 'numeric', minute: '2-digit',
    });

  return (
    <View style={[styles.container, { backgroundColor: colors.background }]}>
      <View style={[styles.header, { paddingTop: topPad + 12, backgroundColor: colors.primary }]}>
        <TouchableOpacity onPress={() => router.back()} style={styles.backBtn} hitSlop={{ top: 8, bottom: 8, left: 8, right: 8 }}>
          <Ionicons name="chevron-back" size={24} color="rgba(255,255,255,0.9)" />
        </TouchableOpacity>
        <Text style={styles.headerTitle}>Assessment Detail</Text>
        <TouchableOpacity onPress={handleDelete} style={styles.deleteBtn}>
          <Feather name="trash-2" size={18} color="rgba(255,255,255,0.7)" />
        </TouchableOpacity>
      </View>

      <ScrollView
        contentContainerStyle={[styles.scrollContent, { paddingBottom: bottomPad + 40 }]}
        showsVerticalScrollIndicator={false}
      >
        {/* Header */}
        <View
          style={[
            styles.heroCard,
            {
              backgroundColor: { green: colors.greenBg, yellow: colors.yellowBg, orange: colors.orangeBg, red: colors.redBg }[assessment.classification],
              borderColor: { green: colors.greenBorder, yellow: colors.yellowBorder, orange: colors.orangeBorder, red: colors.redBorder }[assessment.classification],
              borderRadius: colors.radius,
            },
          ]}
        >
          <ClassificationBadge classification={assessment.classification} size="lg" />
          <Text style={[styles.classTitle, { color: classColor }]}>{info.title}</Text>
          <Text style={[styles.dateText, { color: colors.mutedForeground }]}>
            {formatDate(assessment.createdAt)}
          </Text>
          {regionLabel && (
            <Text style={[styles.regionText, { color: colors.foreground }]}>{regionLabel}</Text>
          )}
        </View>

        {/* Reasons */}
        <Section title="Why you received this result">
          {assessment.classificationReasons.map((r, i) => (
            <View key={i} style={styles.reasonRow}>
              <Ionicons name="information-circle-outline" size={15} color={classColor} />
              <Text style={[styles.reasonText, { color: colors.mutedForeground }]}>{r}</Text>
            </View>
          ))}
        </Section>

        {/* Modifications */}
        {assessment.modifications.length > 0 && (
          <Section title="Training modifications">
            {assessment.modifications.map(id => {
              const opt = MODIFICATION_OPTIONS.find(o => o.id === id);
              return opt ? (
                <View key={id} style={styles.reasonRow}>
                  <Ionicons name="checkmark-circle-outline" size={15} color={colors.accent} />
                  <Text style={[styles.reasonText, { color: colors.foreground }]}>{opt.label}</Text>
                </View>
              ) : null;
            })}
          </Section>
        )}

        {/* Session check-ins */}
        {assessment.sessionCheckins.length > 0 && (
          <Section title="Session check-ins">
            {assessment.sessionCheckins.map(ci => {
              const timingLabel = { warmup: 'After warm-up', first_set: 'After first working set', halfway: 'Halfway through', post_session: 'Post-session' }[ci.timing];
              return (
                <View key={ci.id} style={styles.checkinRow}>
                  <View style={styles.checkinHeader}>
                    <Text style={[styles.checkinTiming, { color: colors.foreground }]}>{timingLabel}</Text>
                    <ClassificationBadge classification={ci.updatedClassification} size="sm" />
                  </View>
                  <Text style={[styles.checkinDetail, { color: colors.mutedForeground }]}>
                    Symptoms: {ci.symptoms} | ROM: {ci.rangeOfMotion} | Strength: {ci.strength}
                  </Text>
                </View>
              );
            })}
          </Section>
        )}

        {/* Follow-up */}
        {assessment.followUp ? (
          <Section title="24-hour follow-up">
            <Text style={[styles.reasonText, { color: colors.foreground }]}>
              Response: {assessment.followUp.nextDayResponse.replace(/_/g, ' ')}
            </Text>
            <Text style={[styles.reasonText, { color: colors.mutedForeground }]}>
              Completed {formatDate(assessment.followUp.completedAt)}
            </Text>
          </Section>
        ) : (
          <TouchableOpacity
            onPress={() => router.push(`/follow-up/${assessment.id}`)}
            style={[styles.followUpBtn, { backgroundColor: colors.card, borderColor: colors.border, borderRadius: colors.radius }]}
            testID="add-followup-btn"
          >
            <Ionicons name="calendar-outline" size={18} color={colors.accent} />
            <Text style={[styles.followUpBtnText, { color: colors.foreground }]}>
              Add 24-Hour Follow-Up
            </Text>
            <Ionicons name="chevron-forward" size={16} color={colors.mutedForeground} />
          </TouchableOpacity>
        )}
      </ScrollView>
    </View>
  );
}

